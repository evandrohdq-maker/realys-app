export const salaryText = (j) => {
  const v = 'R$ ' + Number(j.salary).toFixed(2).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return `${v} ${j.salaryUnit || 'por mês'}`;
};
